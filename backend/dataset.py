import os
import json
import torch
from torch.utils.data import Dataset
import numpy as np

# NOTE: MATExtractor (mat_extract.py) is retired from the training pipeline.
# Training now uses 2D camera-projected keypoints from Blender (keypoints_2d in joints.jsonl)
# which match exactly what YOLOv8-pose outputs at inference time.

# Static anatomical adjacency — encodes the actual skeletal graph.
# Matches the bonePairs in train_gcn.py and the JS render engine exactly.
# 0:Pelvis, 1:R_Hip, 2:R_Knee, 3:R_Ankle, 4:L_Hip, 5:L_Knee, 6:L_Ankle,
# 7:Spine1, 8:Spine2, 9:Neck, 10:Head, 11:L_Shoulder, 12:L_Elbow, 13:L_Wrist,
# 14:R_Shoulder, 15:R_Elbow, 16:R_Wrist
BONE_PAIRS = [
    (0, 1), (1, 2), (2, 3),      # Right Leg
    (0, 4), (4, 5), (5, 6),      # Left Leg
    (0, 7), (7, 8), (8, 9),      # Spine
    (9, 10),                      # Neck to Head
    (9, 11), (11, 12), (12, 13), # Left Arm
    (9, 14), (14, 15), (15, 16)  # Right Arm
]

GCN_JOINT_NAMES = [
    'Pelvis', 'R_Hip', 'R_Knee', 'R_Ankle',
    'L_Hip', 'L_Knee', 'L_Ankle',
    'Spine1', 'Spine2', 'Neck', 'Head',
    'L_Shoulder', 'L_Elbow', 'L_Wrist',
    'R_Shoulder', 'R_Elbow', 'R_Wrist'
]

def build_static_adj():
    """Build the fixed anatomical adjacency matrix (17x17) with self-loops."""
    adj = np.zeros((17, 17), dtype=np.float32)
    for i in range(17):
        adj[i, i] = 1.0  # self-loop
    for (i, j) in BONE_PAIRS:
        adj[i, j] = 1.0
        adj[j, i] = 1.0
    return adj

STATIC_ADJ = build_static_adj()  # Pre-built once, reused for every sample


class VisionTrackDataset(Dataset):
    def __init__(self, data_dir, transform=None):
        """
        PyTorch Dataset for VisionTrack SemanticGCN.

        Input format (per sample):
          - nodes: (17, 5) float32
              channels: [y_norm, x_norm, r_left=10, r_right=10, visibility=1]
              2D keypoints normalized to [0, 256] via bounding-box normalization,
              matching exactly what the JS inference code does with YOLOv8 outputs.

          - adj: (17, 17) float32
              Static anatomical adjacency matrix (same bone pairs used in JS renderer).

        Target format (per sample):
          - joints: (17, 3) float32
              3D joint positions in Blender space, PELVIS-RELATIVE.
              (All joints minus the Pelvis root position, so Pelvis = [0, 0, 0])

        Requires joints.jsonl entries to have 'keypoints_2d' key (generated by the
        fixed Blender addon). Samples without 'keypoints_2d' are skipped.
        """
        self.data_dir = data_dir
        self.samples = []
        self.transform = transform
        self._parse_directory()

    def _parse_directory(self):
        skipped = 0
        for root, dirs, files in os.walk(self.data_dir):
            if 'joints.jsonl' not in files:
                continue
            joints_file = os.path.join(root, 'joints.jsonl')
            with open(joints_file, 'r') as f:
                for line in f:
                    data = json.loads(line)
                    frame_idx = data['frame']

                    # Only accept samples generated by the FIXED Blender addon
                    # (which includes 2D camera-projected keypoints)
                    if 'keypoints_2d' not in data:
                        skipped += 1
                        continue

                    mask_filename = f"mask_{frame_idx:04d}.png"
                    mask_path = os.path.join(root, mask_filename)

                    if os.path.exists(mask_path):
                        self.samples.append({
                            'keypoints_2d': data['keypoints_2d'],
                            'joints_3d': data.get('joints_3d', data.get('joints', {}))
                        })

        print(f"Loaded {len(self.samples)} valid samples from {self.data_dir}")
        if skipped > 0:
            print(f"  Skipped {skipped} samples without 'keypoints_2d' (old format).")
            print(f"  Re-run the Blender addon to regenerate training data with 2D projections.")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        sample = self.samples[idx]
        keypoints_2d = sample['keypoints_2d']   # dict: bone_name -> [u, v] pixel coords
        joints_3d_dict = sample['joints_3d']    # dict: bone_name -> [x, y, z] world coords

        # ----------------------------------------------------------------
        # 1. Build 2D Input Nodes (17, 5)
        #    Matches exactly what the JS inference code does:
        #      getNormKP() -> bounding box normalization to [0, 256]
        #      gcnNodes[] -> ordered by GCN_JOINT_NAMES
        #      nodesData channels: [y, 256-x, r_left, r_right, conf]
        # ----------------------------------------------------------------
        kps = []
        for name in GCN_JOINT_NAMES:
            uv = keypoints_2d.get(name, [320.0, 240.0])  # fallback: image center
            kps.append([float(uv[0]), float(uv[1])])     # [u=x_pixel, v=y_pixel]

        xs = [k[0] for k in kps]
        ys = [k[1] for k in kps]
        min_x, max_x = min(xs), max(xs)
        min_y, max_y = min(ys), max(ys)
        bw = max(20.0, max_x - min_x)
        bh = max(20.0, max_y - min_y)

        nodes_2d = np.zeros((17, 2), dtype=np.float32)
        for i, kp in enumerate(kps):
            x_norm = max(0.0, min(256.0, ((kp[0] - min_x) / bw) * 256.0))
            y_norm = max(0.0, min(256.0, ((kp[1] - min_y) / bh) * 256.0))
            
            # FIX 1: Channel 0 = X, Channel 1 = Y
            # FIX 2: Standardize to [-1.0, 1.0] zero-centered range
            nodes_2d[i, 0] = (x_norm / 128.0) - 1.0
            nodes_2d[i, 1] = (y_norm / 128.0) - 1.0

        # Append padding channels: r_left=10, r_right=10, visibility=1
        padding = np.zeros((17, 3), dtype=np.float32)
        padding[:, 0] = 10.0
        padding[:, 1] = 10.0
        padding[:, 2] = 1.0
        nodes_5d = np.hstack((nodes_2d, padding))  # (17, 5)

        # ----------------------------------------------------------------
        # 2. Static Anatomical Adjacency Matrix (17, 17)
        # ----------------------------------------------------------------
        adj_matrix = STATIC_ADJ.copy()

        # ----------------------------------------------------------------
        # 3. Build 3D Target Joints (17, 3) — PELVIS-RELATIVE & WebGL Remapped
        # ----------------------------------------------------------------
        target_joints = []
        for name in GCN_JOINT_NAMES:
            if name in joints_3d_dict:
                target_joints.append(joints_3d_dict[name])
            else:
                target_joints.append([0.0, 0.0, 0.0])

        target_joints = np.array(target_joints, dtype=np.float32)  # (17, 3)

        # Subtract Pelvis (index 0) to make all joints pelvis-relative
        pelvis_pos = target_joints[0].copy()
        target_joints = target_joints - pelvis_pos  # Pelvis becomes [0, 0, 0]

        # FIX 3: Convert Blender [X, Y, Z] -> Three.js/WebGL [X, Z, -Y]
        webgl_targets = np.zeros_like(target_joints)
        webgl_targets[:, 0] =  target_joints[:, 0]  # X_webgl = X_blender
        webgl_targets[:, 1] =  target_joints[:, 2]  # Y_webgl = Z_blender (Height)
        webgl_targets[:, 2] = -target_joints[:, 1]  # Z_webgl = -Y_blender (Depth)

        # Convert to tensors
        nodes_tensor  = torch.tensor(nodes_5d,      dtype=torch.float32)
        adj_tensor    = torch.tensor(adj_matrix,    dtype=torch.float32)
        target_tensor = torch.tensor(webgl_targets, dtype=torch.float32)

        # Sanitize NaN/Inf
        nodes_tensor  = torch.nan_to_num(nodes_tensor,  nan=0.0)
        adj_tensor    = torch.nan_to_num(adj_tensor,    nan=0.0)
        target_tensor = torch.nan_to_num(target_tensor, nan=0.0)

        return nodes_tensor, adj_tensor, target_tensor


if __name__ == "__main__":
    print("VisionTrack Dataset Loader Ready (YOLO-aligned 2D keypoint inputs).")
